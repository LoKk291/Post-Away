const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  selectFolder: () => ipcRenderer.invoke('select-folder'),
  readFolder: (folderPath) => ipcRenderer.invoke('read-folder', folderPath),
  compressFolder: (folderPath) => ipcRenderer.invoke('compress-folder', folderPath),
  getSession: () => ipcRenderer.invoke('get-session'),
  getLocalIp: () => ipcRenderer.invoke('get-local-ip'),
  getHostname: () => ipcRenderer.invoke('get-hostname'),
  saveSession: (data) => ipcRenderer.invoke('save-session', data),
  fillPatreon: (data) => ipcRenderer.invoke('fill-patreon', data),
  openPatreon: (profile) => ipcRenderer.invoke('open-patreon', profile),
  copyClipboard: (text) => ipcRenderer.invoke('copy-clipboard', text),
  triggerAutoUpload: (filePath) => ipcRenderer.invoke('trigger-auto-upload', filePath),
  openFolder: (folderPath) => ipcRenderer.invoke('open-folder', folderPath),
  onAutoQueueReady: (callback) => ipcRenderer.on('auto-queue-ready', callback),
  onAutoQueueDone: (callback) => ipcRenderer.on('auto-queue-done', callback),
  fetchPatreonLinks: (url, posts) => ipcRenderer.invoke('fetch-patreon-links', url, posts),
  deleteRars: (folderPaths) => ipcRenderer.invoke('delete-rars', folderPaths),
  getSiblingFolders: (folderPath) => ipcRenderer.invoke('get-sibling-folders', folderPath),
  checkFolderExists: (folderPath) => ipcRenderer.invoke('check-folder-exists', folderPath),
  checkIsDirectory: (folderPath) => ipcRenderer.invoke('check-is-directory', folderPath),
  mergeFolder: (folderPath) => ipcRenderer.invoke('merge-folder', folderPath),
  getOrgFolders: (basePath) => ipcRenderer.invoke('get-org-folders', basePath),
  createMonthFolder: (basePath, monthName) => ipcRenderer.invoke('create-month-folder', basePath, monthName),
  createDateFolder: (basePath, monthName, dateName) => ipcRenderer.invoke('create-date-folder', basePath, monthName, dateName),
  moveCharacterFolder: (charPath, targetBase, targetNova, month, date) => ipcRenderer.invoke('move-character-folder', charPath, targetBase, targetNova, month, date),
  moveOrganizedCharacter: (charName, sourceMonth, sourceDate, targetMonth, targetDate, baseOrgPath, novaOrgPath) => ipcRenderer.invoke('move-organized-character', charName, sourceMonth, sourceDate, targetMonth, targetDate, baseOrgPath, novaOrgPath),
  deleteFolder: (folderPath) => ipcRenderer.invoke('delete-folder', folderPath),
  renameFolder: (folderPath, newName) => ipcRenderer.invoke('rename-folder', folderPath, newName),
  openInExplorer: (folderPath) => ipcRenderer.invoke('open-in-explorer', folderPath),
  searchCharacters: (query, basePath, outputPath) => ipcRenderer.invoke('search-characters', query, basePath, outputPath),
  getFolderImages: (folderPath) => ipcRenderer.invoke('get-folder-images', folderPath),
  getNovaFolderPath: (nickyPath, baseOrgPath, novaOrgPath) => ipcRenderer.invoke('get-nova-folder-path', nickyPath, baseOrgPath, novaOrgPath),
  renameFile: (oldPath, newName) => ipcRenderer.invoke('rename-file', oldPath, newName),
  deleteFileTrash: (filePath) => ipcRenderer.invoke('delete-file-trash', filePath),
  restoreFileTrash: (trashPath, originalPath) => ipcRenderer.invoke('restore-file-trash', trashPath, originalPath),
  sendToRuleX: (basePath, rulexPath, monthName, dateName) => ipcRenderer.invoke('send-to-rulex', basePath, rulexPath, monthName, dateName),
  sendToYaSubido: (basePath, yaSubidoPath, monthName, dateName) => ipcRenderer.invoke('send-to-yasubido', basePath, yaSubidoPath, monthName, dateName),
  onUploadComplete: (callback) => ipcRenderer.on('upload-complete', callback),
  fillTwitter: (data) => ipcRenderer.invoke('fill-twitter', data),
  openTwitter: (profile, targetUrl) => ipcRenderer.invoke('open-twitter', profile, targetUrl),
  getWatermarkImages: (folderPath) => ipcRenderer.invoke('get-watermark-images', folderPath),
  setTwitterFeed: (feedData) => ipcRenderer.invoke('set-twitter-feed', feedData),
  onTwitterPostUpdated: (callback) => ipcRenderer.on('twitter-post-updated', callback),
  getCounterpartFolder: (folderPath, currentProfile) => ipcRenderer.invoke('get-counterpart-folder', folderPath, currentProfile)
});
